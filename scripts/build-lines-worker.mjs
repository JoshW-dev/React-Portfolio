// Writes public/film/lines-worker.js: the Earth lines worker (components/orbit/earthLines.worker.ts)
// with the two modules it needs, as one plain script. Turbopack copies a worker's .ts source
// as a file instead of bundling it, so this runs before `next dev` and `next build` instead.
// It only strips types: the three files import nothing else, and their code needs no bundler.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import ts from "typescript";

const root = path.dirname(path.dirname(new URL(import.meta.url).pathname));
const files = ["components/orbit/orbitFrame.ts", "components/orbit/earthLines.ts", "components/orbit/earthLines.worker.ts"];
const body = files
  .map((f) => {
    const src = readFileSync(path.join(root, f), "utf8");
    const js = ts.transpileModule(src, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext, removeComments: true } }).outputText;
    return js
      .split("\n")
      .filter((l) => !/^\s*import\s/.test(l) && !/^\s*export\s*\{\s*\};?\s*$/.test(l))
      .map((l) => l.replace(/^export\s+/, ""))
      .join("\n");
  })
  .join("\n");
const out = path.join(root, "public/film/lines-worker.js");
writeFileSync(out, `// Generated by scripts/build-lines-worker.mjs. Do not edit.\n"use strict";\n(() => {\n${body}\n})();\n`);
console.log("wrote", path.relative(root, out));
